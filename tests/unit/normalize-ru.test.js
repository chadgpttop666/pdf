import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { cardinal, fromRoman, normalizeRussian, ordinal, plural } from '../../extension/src/tts/normalize-ru.js';

const say = (text) => normalizeRussian(text).text;

describe('числительные', () => {
  it('количественные', () => {
    assert.equal(cardinal(1928), 'тысяча девятьсот двадцать восемь');
    assert.equal(cardinal(2010), 'две тысячи десять');
    assert.equal(cardinal(592, 'f'), 'пятьсот девяносто две');
    assert.equal(cardinal(21, 'f'), 'двадцать одна');
    assert.equal(cardinal(5000000), 'пять миллионов');
  });

  it('порядковые: последнее слово склоняется', () => {
    assert.equal(ordinal(1928, 'prep'), 'тысяча девятьсот двадцать восьмом');
    assert.equal(ordinal(1945, 'gen'), 'тысяча девятьсот сорок пятого');
    assert.equal(ordinal(2000, 'prep'), 'двухтысячном');
    assert.equal(ordinal(2010, 'nom'), 'две тысячи десятый');
    assert.equal(ordinal(1900, 'gen'), 'тысяча девятисотого');
    assert.equal(ordinal(40, 'nom'), 'сороковой');
    assert.equal(ordinal(2, 'nom'), 'второй');
    assert.equal(ordinal(3, 'prep'), 'третьем');
    assert.equal(ordinal(3, 'nom', 'f'), 'третья');
    assert.equal(ordinal(5, 'acc', 'f'), 'пятую');
    assert.equal(ordinal(1990, 'prep', 'pl'), 'тысяча девятьсот девяностых');
  });

  it('согласование и римские', () => {
    assert.deepEqual([1, 2, 5, 11, 22, 592].map((n) => plural(n, ['страница', 'страницы', 'страниц'])), [
      'страница', 'страницы', 'страниц', 'страниц', 'страницы', 'страницы',
    ]);
    assert.equal(fromRoman('XIX'), 19);
    assert.equal(fromRoman('IIII'), null);
    assert.equal(fromRoman('Hello'), null);
  });
});

describe('текст для нейроголоса', () => {
  it('годы со словом «год» — в падеже этого слова', () => {
    assert.equal(say('В 1928 году провели опыт.'), 'В тысяча девятьсот двадцать восьмом году провели опыт.');
    assert.equal(say('весной 1948 года'), 'весной тысяча девятьсот сорок восьмого года');
    assert.equal(say('к 1950 году'), 'к тысяча девятьсот пятидесятому году');
    assert.equal(say('в 1945–1946 годах'), 'в тысяча девятьсот сорок пятом — тысяча девятьсот сорок шестом годах');
  });

  it('«г.» и «гг.» — падеж по предлогу, слово раскрывается', () => {
    assert.equal(say('в 1947 г. он'), 'в тысяча девятьсот сорок седьмом году он');
    assert.equal(say('с 1945 г. до'), 'с тысяча девятьсот сорок пятого года до');
    assert.equal(say('Конституция 1993 г.'), 'Конституция тысяча девятьсот девяносто третьего года.');
    assert.equal(say('в 1945–1946 гг.'), 'в тысяча девятьсот сорок пятом — тысяча девятьсот сорок шестом годах.');
  });

  it('год без слова «год» — по предлогу или слову-дате', () => {
    assert.equal(
      say('С осени 1945 по конец 1946 года'),
      'С осени тысяча девятьсот сорок пятого по конец тысяча девятьсот сорок шестого года'
    );
    assert.equal(say('в 1945 Эрхард'), 'в тысяча девятьсот сорок пятом Эрхард');
    assert.equal(say('в мае 1945, когда'), 'в мае тысяча девятьсот сорок пятого, когда');
    assert.equal(say('в 2000 рублях'), 'в 2000 рублях', 'не год — не трогаем');
    assert.equal(say('М., 2010.'), 'М., 2010.', 'без контекста число читает сам голос');
  });

  it('наращения, десятилетия, даты, века, главы', () => {
    assert.equal(say('5-й том, 2-го числа, в 3-м классе'), 'пятый том, второго числа, в третьем классе');
    assert.equal(say('1990-е годы и в 1990-х'), 'тысяча девятьсот девяностые годы и в тысяча девятьсот девяностых');
    assert.equal(say('родился 1 мая'), 'родился первого мая');
    assert.equal(say('в XIX веке и XX в.'), 'в девятнадцатом веке и двадцатого века.');
    assert.equal(say('Глава I. В главе 5'), 'Глава первая. В главе пятой');
    assert.equal(say('Том III'), 'Том третий');
  });

  it('сокращения и единицы с согласованием', () => {
    assert.equal(say('(т. е., трех зон)'), '(то есть, трех зон)');
    assert.equal(say('и т. д. Дальше'), 'и так далее. Дальше');
    assert.equal(say('Проф. Иванов, см. рис. 2'), 'Профессор Иванов, смотри рисунок 2');
    assert.equal(say('592 с. — 1000 экз.'), 'пятьсот девяносто две страницы — тысяча экземпляров.');
    assert.equal(say('на 15% больше, 21 руб., 5 см'), 'на пятнадцать процентов больше, двадцать один рубль, пять сантиметров');
    assert.equal(say('№ 5'), 'номер 5');
  });

  it('замены описаны отрезками исходного текста', () => {
    const { text, segments } = normalizeRussian('В 1928 году, т. е. давно.');
    assert.equal(text, 'В тысяча девятьсот двадцать восьмом году, то есть давно.');
    assert.deepEqual(
      segments.map(({ start, end, spoken }) => ['В 1928 году, т. е. давно.'.slice(start, end), spoken]),
      [['1928', 'тысяча девятьсот двадцать восьмом'], ['т. е.', 'то есть']]
    );
  });
});
