// Сколько сэмплеров TeraTTS держать — это самая тяжёлая часть синтеза
// (≈ 1 с работы на секунду речи на слабом процессоре; вокодер — втрое
// меньше). Каждый сэмплер — свой поток и ещё ≈ 1 ГБ памяти.
//
// Речь синтезируется на обычной скорости (ускоряет проигрыватель), поэтому
// на 2× синтез должен успевать вдвое быстрее. Один сэмплер на 2× не
// успевал: звучал первый короткий кусок фразы — пара слов, — и голос
// замолкал, пока готовился следующий.

/**
 * @param choice настройка: 'auto' | '1' | '2' | '3'
 * @param rate скорость чтения
 * @param lagging синтез уже не успевал за речью
 * @param cores число ядер процессора
 */
export function samplerCount(choice, { rate = 1, lagging = false, cores = 4 } = {}) {
  if (choice !== 'auto') return Math.min(3, Math.max(1, Math.round(Number(choice)) || 1));
  let wanted = rate >= 1.3 || lagging ? 2 : 1;
  if (rate >= 2.2 && cores >= 8) wanted = 3;
  // Ещё по ядру нужно вокодеру, ударениям и самой странице.
  return Math.max(1, Math.min(wanted, cores - 2));
}
